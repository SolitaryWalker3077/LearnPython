# 变量
# 给定四个分数, 67.5, 89.0, 12.9, 32.2 , 编写代码, 求这四个分数的方差.
# ps: 方差的计算过程: 取每一项, 减去平均值, 计算平方, 再求和, 最后除以 (项数 - 1)
# **在Python当中表示乘方运算  **2即表示平方运算
avg = (67.5 + 89 + 12.9 + 32.2) / 4  # 50.4
total = (67.5 - avg) ** 2 + (89 - avg) ** 2 + (12.9 - avg) ** 2 + (32.2 - avg) ** 2 # 292.41 + 1489.96 + 1,406.25 + 331.24
result = total / 3
print(result)